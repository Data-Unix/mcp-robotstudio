// Lab license tooling for MCP-ROBOTSTUDIO PRO (ECDSA P-256, WebCrypto-compatible).
//   node scripts/license-lab.mjs keygen            -> .license-lab/private.jwk (gitignored) + src/license-public-key.ts
//   node scripts/license-lab.mjs issue <sub> [days] -> prints a signed PRO token
// The private key never leaves .license-lab/. A billing backend (ExtPay / Stripe
// webhook) would sign the same token format with its own key.
import { webcrypto as crypto } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LAB = path.join(ROOT, ".license-lab");
const PRIV = path.join(LAB, "private.jwk");
const PUB_TS = path.join(ROOT, "src", "license-public-key.ts");
const ALG = { name: "ECDSA", namedCurve: "P-256" };

const b64url = (buf) => Buffer.from(buf).toString("base64url");

export async function issueToken(privateJwk, sub, days = 365, now = Date.now()) {
  const key = await crypto.subtle.importKey("jwk", privateJwk, ALG, false, ["sign"]);
  const payload = { aud: "mcp-robotstudio-pro", plan: "pro", sub, iat: Math.floor(now / 1000), exp: Math.floor(now / 1000) + days * 86400 };
  const body = b64url(JSON.stringify(payload));
  const sig = await crypto.subtle.sign({ name: "ECDSA", hash: "SHA-256" }, key, new TextEncoder().encode(body));
  return `${body}.${b64url(sig)}`;
}

export async function generateKeyPair() {
  const kp = await crypto.subtle.generateKey(ALG, true, ["sign", "verify"]);
  return {
    privateJwk: await crypto.subtle.exportKey("jwk", kp.privateKey),
    publicJwk: await crypto.subtle.exportKey("jwk", kp.publicKey),
  };
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  const [cmd, sub, days] = process.argv.slice(2);
  if (cmd === "keygen") {
    if (fs.existsSync(PRIV)) throw new Error(`${PRIV} already exists; delete it to rotate the key`);
    const { privateJwk, publicJwk } = await generateKeyPair();
    fs.mkdirSync(LAB, { recursive: true });
    fs.writeFileSync(PRIV, JSON.stringify(privateJwk));
    const { kty, crv, x, y } = publicJwk;
    fs.writeFileSync(
      PUB_TS,
      `// Generated by scripts/license-lab.mjs keygen. Public half only.\nexport const LICENSE_PUBLIC_KEY: JsonWebKey = ${JSON.stringify({ kty, crv, x, y })};\n`,
    );
    process.stdout.write(`keys written: ${path.relative(ROOT, PRIV)} (private, gitignored), ${path.relative(ROOT, PUB_TS)}\n`);
  } else if (cmd === "issue") {
    if (!sub) throw new Error("usage: issue <subject> [days]");
    const token = await issueToken(JSON.parse(fs.readFileSync(PRIV, "utf8")), sub, Number(days ?? 365));
    process.stdout.write(`${token}\n`);
  } else {
    process.stderr.write("usage: node scripts/license-lab.mjs keygen | issue <subject> [days]\n");
    process.exit(2);
  }
}
